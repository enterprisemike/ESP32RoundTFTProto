#!/usr/bin/env python3
"""Convert a needle sprite PNG (RGBA, needle pointing UP, pivot given in source
pixels) into RGB565 colour + 8-bit alpha C arrays for rotated blitting.

Crops to the opaque bounding box (plus 1px pad) and emits the pivot location
relative to the crop.

Usage:
    python3 tools/needle2header.py <input.png> <array_name> <pivot_x> <pivot_y> <output.h>

Example (pivot at the centre of a 466x466 canvas):
    python3 tools/needle2header.py \
        assets/needle_main.png needle_main 232.5 232.5 include/assets/needle_main.h
"""

import sys
from pathlib import Path

from PIL import Image


def rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main() -> None:
    if len(sys.argv) != 6:
        sys.exit(__doc__)

    src, name = sys.argv[1], sys.argv[2]
    pivot_x, pivot_y = float(sys.argv[3]), float(sys.argv[4])
    dest = Path(sys.argv[5])

    img = Image.open(src).convert("RGBA")
    bbox = img.getchannel("A").getbbox()
    if bbox is None:
        sys.exit("Image is fully transparent")
    x0 = max(0, bbox[0] - 1)
    y0 = max(0, bbox[1] - 1)
    x1 = min(img.width, bbox[2] + 1)
    y1 = min(img.height, bbox[3] + 1)
    img = img.crop((x0, y0, x1, y1))
    pivot_x -= x0
    pivot_y -= y0

    w, h = img.size
    pixels = list(img.getdata())

    lines = [
        "// Auto-generated by tools/needle2header.py — do not edit.",
        f"// Source: {src} (cropped from ({x0},{y0}))",
        "#pragma once",
        "#include <pgmspace.h>",
        "",
        f"#define {name.upper()}_WIDTH {w}",
        f"#define {name.upper()}_HEIGHT {h}",
        f"#define {name.upper()}_PIVOT_X {pivot_x}f",
        f"#define {name.upper()}_PIVOT_Y {pivot_y}f",
        "",
        f"static const uint16_t {name}[{w * h}] PROGMEM = {{",
    ]
    for i in range(0, len(pixels), 16):
        row = ", ".join(f"0x{rgb565(*p[:3]):04X}" for p in pixels[i : i + 16])
        lines.append(f"    {row},")
    lines.append("};")
    lines.append("")
    lines.append(f"static const uint8_t {name}_alpha[{w * h}] PROGMEM = {{")
    for i in range(0, len(pixels), 24):
        row = ", ".join(f"{p[3]}" for p in pixels[i : i + 24])
        lines.append(f"    {row},")
    lines.append("};")

    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines) + "\n")
    print(f"Wrote {dest} ({w}x{h}, pivot {pivot_x},{pivot_y}, {w * h * 3 / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
