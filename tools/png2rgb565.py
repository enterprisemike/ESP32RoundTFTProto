#!/usr/bin/env python3
"""Convert a gauge background PNG to an RGB565 C header for Arduino_GFX.

Transparent pixels are composited onto black (ideal for AMOLED).

Usage:
    python3 tools/png2rgb565.py "<input.png>" <array_name> <output.h>

Example:
    python3 tools/png2rgb565.py \
        "assets/gauge_current.png" gauge_current_bg include/assets/gauge_current_bg.h
"""

import sys
from pathlib import Path

from PIL import Image


def rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)

    src, name, dest = sys.argv[1], sys.argv[2], Path(sys.argv[3])

    img = Image.open(src)
    if img.mode != "RGBA":
        img = img.convert("RGBA")
    black = Image.new("RGBA", img.size, (0, 0, 0, 255))
    img = Image.alpha_composite(black, img).convert("RGB")

    w, h = img.size
    pixels = list(img.getdata())

    lines = [
        "// Auto-generated by tools/png2rgb565.py — do not edit.",
        f"// Source: {src}",
        "#pragma once",
        "#include <pgmspace.h>",
        "",
        f"#define {name.upper()}_WIDTH {w}",
        f"#define {name.upper()}_HEIGHT {h}",
        "",
        f"static const uint16_t {name}[{w * h}] PROGMEM = {{",
    ]
    for i in range(0, len(pixels), 16):
        row = ", ".join(f"0x{rgb565(*p):04X}" for p in pixels[i : i + 16])
        lines.append(f"    {row},")
    lines.append("};")

    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines) + "\n")
    print(f"Wrote {dest} ({w}x{h}, {w * h * 2 / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
